<?php

declare(strict_types=1);

namespace App\Command;

use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Attribute\Option;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Style\SymfonyStyle;
use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\VarExporter\VarExporter;

/**
 * The output schemas of docs/specs/mcp.md section 3: each root with every `$ref` target copied into its `$defs`.
 */
#[AsCommand(name: 'app:schema:bundle', description: 'Generates src/Mcp/BundledSchemas.php from docs/specs/schemas')]
final class BundleSchemasCommand
{
    private const string SCHEMA_DIRECTORY = 'docs/specs/schemas';
    private const string OUTPUT_FILE = 'src/Mcp/BundledSchemas.php';

    /** Constant name => schema file with an optional JSON pointer. */
    private const array ROOTS = [
        'REPOSITORY_PAGE' => 'lists.schema.json#/$defs/RepositoryPage',
        'REVIEW_PAGE' => 'lists.schema.json#/$defs/ReviewPage',
        'REQUEST_PAGE' => 'lists.schema.json#/$defs/RequestPage',
        'UPDATES_PAGE' => 'updates-page.schema.json',
        'REQUEST' => 'request.schema.json',
        'REQUEST_COMMAND_RESULT' => 'request-command-result.schema.json',
        'LINK_COMMITS_RESULT' => 'link-commits-result.schema.json',
        'LINK_PULL_REQUEST_RESULT' => 'link-pull-request-result.schema.json',
    ];

    /** Keys that identify a file. A bundled copy lives inside another document. */
    private const array FILE_KEYS = ['$schema', '$id', '$defs'];

    /** @var array<string, array<string, mixed>> Decoded schema files by name */
    private array $documents = [];

    public function __construct(
        #[Autowire('%kernel.project_dir%')] private readonly string $projectDir,
        private readonly Filesystem $filesystem,
    ) {
    }

    public function __invoke(SymfonyStyle $io, #[Option('Fail when the file differs, without writing it')] bool $check = false): int
    {
        $outputPath = "{$this->projectDir}/".self::OUTPUT_FILE;
        $php = $this->generate();

        if ($check) {
            if ($this->filesystem->exists($outputPath) && $this->filesystem->readFile($outputPath) === $php) {
                $io->success(self::OUTPUT_FILE.' is up to date.');

                return Command::SUCCESS;
            }

            $io->error(self::OUTPUT_FILE.' differs from the schema files. Run app:schema:bundle.');

            return Command::FAILURE;
        }

        $this->filesystem->dumpFile($outputPath, $php);
        $io->success(self::OUTPUT_FILE.' is generated.');

        return Command::SUCCESS;
    }

    private function generate(): string
    {
        $this->documents = [];
        $constants = [];

        foreach (self::ROOTS as $constant => $root) {
            $exported = str_replace("\n", "\n    ", VarExporter::export($this->bundle($root)));
            $constants[] = "    /** {$root} */\n    public const array {$constant} = {$exported};";
        }

        return "<?php\n\ndeclare(strict_types=1);\n\nnamespace App\\Mcp;\n\n/**\n * Generated by app:schema:bundle from "
            .self::SCHEMA_DIRECTORY.". Do not edit.\n */\nfinal class BundledSchemas\n{\n".implode("\n\n", $constants)."\n}\n";
    }

    /**
     * @return array<string, mixed>
     */
    private function bundle(string $root): array
    {
        [$file, $pointer] = self::splitReference($root, '');
        $definitions = [];
        $sources = [];
        $schema = $this->rewrite(array_diff_key($this->resolve($file, $pointer), array_flip(self::FILE_KEYS)), $file, $definitions, $sources);
        \assert(\is_array($schema));
        ksort($definitions);

        return [] === $definitions ? $schema : $schema + ['$defs' => $definitions];
    }

    /**
     * Rewrites each `$ref` to `#/$defs/<Name>` and copies its target into $definitions, once per name.
     *
     * @param array<string, mixed>  $definitions
     * @param array<string, string> $sources     The reference of each definition name
     */
    private function rewrite(mixed $node, string $file, array &$definitions, array &$sources): mixed
    {
        if (!\is_array($node)) {
            return $node;
        }

        foreach ($node as $key => $value) {
            if ('$ref' !== $key || !\is_string($value)) {
                $node[$key] = $this->rewrite($value, $file, $definitions, $sources);
                continue;
            }

            [$targetFile, $targetPointer] = self::splitReference($value, $file);
            $name = $this->definitionName($targetFile, $targetPointer);
            $source = "{$targetFile}#{$targetPointer}";

            if (!isset($sources[$name])) {
                $sources[$name] = $source;
                $definitions[$name] = $this->rewrite(array_diff_key($this->resolve($targetFile, $targetPointer), array_flip(self::FILE_KEYS)), $targetFile, $definitions, $sources);
            } elseif ($sources[$name] !== $source) {
                throw new \LogicException("The definition name {$name} stands for {$sources[$name]} and {$source}.");
            }

            $node[$key] = "#/\$defs/{$name}";
        }

        return $node;
    }

    /**
     * @return array{string, string} The file, and the JSON pointer: '' for the root
     */
    private static function splitReference(string $reference, string $currentFile): array
    {
        [$file, $pointer] = explode('#', $reference, 2) + [1 => ''];

        return ['' === $file ? $currentFile : $file, $pointer];
    }

    /**
     * A file root takes its `title`, a definition its key.
     */
    private function definitionName(string $file, string $pointer): string
    {
        $name = '' === $pointer
            ? $this->document($file)['title'] ?? null
            : (1 === preg_match('#^/\$defs/([A-Za-z][A-Za-z0-9]*)$#D', $pointer, $match) ? $match[1] : null);

        if (!\is_string($name) || 1 !== preg_match('/^[A-Za-z][A-Za-z0-9]*$/D', $name)) {
            throw new \LogicException("The \$ref {$file}#{$pointer} has no definition name.");
        }

        return $name;
    }

    /**
     * @return array<string, mixed>
     */
    private function resolve(string $file, string $pointer): array
    {
        $document = $this->document($file);

        if ('' === $pointer) {
            return $document;
        }

        $name = substr($pointer, \strlen('/$defs/'));
        $definition = $document['$defs'][$name] ?? null;

        return \is_array($definition) ? $definition : throw new \LogicException("{$file}#{$pointer} does not exist.");
    }

    /**
     * @return array<string, mixed>
     */
    private function document(string $file): array
    {
        if (!isset($this->documents[$file])) {
            $document = json_decode($this->filesystem->readFile("{$this->projectDir}/".self::SCHEMA_DIRECTORY."/{$file}"), true, flags: \JSON_THROW_ON_ERROR);
            $this->documents[$file] = \is_array($document) ? $document : throw new \LogicException("{$file} is not a JSON object.");
        }

        return $this->documents[$file];
    }
}
